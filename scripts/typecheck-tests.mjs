#!/usr/bin/env node
// Typecheck test code that the package's own tsconfig leaves out (#337).
//
// Most apps/* tsconfig.json files say `"include": ["src"], "exclude": [..., "test"]` so that
// `tsc` builds only shipped code. That also meant nothing ever typechecked test/ (fixtures, DB
// suites): vitest strips types without checking them, so type errors in tests never failed CI.
//
// This script AUTO-DISCOVERS every apps/* and packages/* directory that has a tsconfig.json AND a
// test/ directory the tsconfig does not include, and runs `tsc --noEmit` over src + test with a
// transient tsconfig that extends the package's own (same compiler options, same strictness). The
// transient file is written beside the package tsconfig (so node_modules/@types resolve exactly as
// for the package) and removed afterwards. A new app is covered the day it lands; nothing to list.
//
// Usage:
//   node scripts/typecheck-tests.mjs                 # every discovered package
//   node scripts/typecheck-tests.mjs bastion-api api # only these (directory names)
//   TYPECHECK_TESTS_CONCURRENCY=2 node scripts/typecheck-tests.mjs
//
// Exits 1 when any package has a type error in src or test.

import { spawn } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TRANSIENT = 'tsconfig.typecheck-tests.json';
const started = Date.now();
const log = (msg) =>
  process.stdout.write(
    `[typecheck-tests +${((Date.now() - started) / 1000).toFixed(1)}s] ${msg}\n`,
  );

/** JSON with comments and trailing commas, as tsconfig allows. */
function readTsconfig(path) {
  const text = readFileSync(path, 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:"'])\/\/.*$/gm, '$1')
    .replace(/,(\s*[}\]])/g, '$1');
  return JSON.parse(text);
}

/** Every package dir whose tsconfig leaves an existing test/ directory out. */
export function discover(root = ROOT) {
  const out = [];
  for (const group of ['apps', 'packages']) {
    const base = join(root, group);
    if (!existsSync(base)) continue;
    for (const name of readdirSync(base).sort()) {
      const dir = join(base, name);
      const tsconfig = join(dir, 'tsconfig.json');
      const test = join(dir, 'test');
      if (!existsSync(tsconfig) || !existsSync(test) || !statSync(test).isDirectory()) continue;
      const cfg = readTsconfig(tsconfig);
      const include = cfg.include ?? ['**/*'];
      const exclude = cfg.exclude ?? [];
      const covered =
        include.some((p) => p === 'test' || p.startsWith('test/') || p === '**/*' || p === '.') &&
        !exclude.includes('test');
      if (!covered) out.push({ group, name, dir, include });
    }
  }
  return out;
}

function hasTs(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules') continue;
    const p = join(dir, entry.name);
    if (entry.isDirectory() ? hasTs(p) : /\.(ts|tsx|mts|cts)$/.test(entry.name)) return true;
  }
  return false;
}

function runTsc(pkg) {
  return new Promise((resolveRun) => {
    const tscBin = join(ROOT, 'node_modules', 'typescript', 'bin', 'tsc');
    const tsc = existsSync(join(pkg.dir, 'node_modules', 'typescript', 'bin', 'tsc'))
      ? join(pkg.dir, 'node_modules', 'typescript', 'bin', 'tsc')
      : tscBin;
    const child = spawn(process.execPath, [tsc, '--noEmit', '--pretty', 'false', '-p', TRANSIENT], {
      cwd: pkg.dir,
    });
    let output = '';
    const collect = (d) => {
      output += d;
    };
    child.stdout.on('data', collect);
    child.stderr.on('data', collect);
    child.on('close', (code) => resolveRun({ code: code ?? 1, output }));
  });
}

async function check(pkg) {
  const label = `${pkg.group}/${pkg.name}`;
  if (!hasTs(join(pkg.dir, 'test'))) {
    log(`${label}: test/ has no TypeScript, skipped`);
    return { label, errors: 0, output: '' };
  }
  const transientPath = join(pkg.dir, TRANSIENT);
  const include = [...new Set([...pkg.include, 'test'])];
  writeFileSync(
    transientPath,
    `${JSON.stringify(
      {
        // Generated by scripts/typecheck-tests.mjs for one run and removed afterwards (#337).
        extends: './tsconfig.json',
        compilerOptions: {
          noEmit: true,
          rootDir: '.',
          composite: false,
          incremental: false,
          declaration: false,
          declarationMap: false,
        },
        include,
        exclude: ['node_modules', 'dist'],
      },
      null,
      2,
    )}\n`,
  );
  const t0 = Date.now();
  log(`${label}: typechecking ${include.join(' + ')} ...`);
  try {
    const { code, output } = await runTsc(pkg);
    const errors = (output.match(/error TS\d+/g) ?? []).length;
    log(
      `${label}: ${code === 0 ? 'clean' : `${errors || 'some'} error(s)`} (${((Date.now() - t0) / 1000).toFixed(1)}s)`,
    );
    return { label, errors: code === 0 ? 0 : Math.max(errors, 1), output };
  } finally {
    rmSync(transientPath, { force: true });
  }
}

async function main() {
  const only = new Set(process.argv.slice(2));
  const pkgs = discover().filter((p) => only.size === 0 || only.has(p.name));
  if (only.size > 0) {
    const missing = [...only].filter((n) => !pkgs.some((p) => p.name === n));
    if (missing.length)
      log(`not a package with an unchecked test/ directory: ${missing.join(', ')}`);
  }
  log(
    `${pkgs.length} package(s) with test code their tsconfig leaves out; typechecking src + test for each`,
  );
  const concurrency = Math.max(1, Number(process.env.TYPECHECK_TESTS_CONCURRENCY ?? 4));
  const results = [];
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(concurrency, pkgs.length) }, async () => {
      while (next < pkgs.length) results.push(await check(pkgs[next++]));
    }),
  );
  const failed = results.filter((r) => r.errors > 0).sort((a, b) => a.label.localeCompare(b.label));
  for (const r of failed) {
    process.stdout.write(`\n--- ${r.label} ---\n${r.output.trim()}\n`);
  }
  const total = failed.reduce((n, r) => n + r.errors, 0);
  log(
    failed.length === 0
      ? `all ${results.length} package(s) clean`
      : `${total} error(s) in ${failed.length} package(s): ${failed.map((r) => r.label).join(', ')}`,
  );
  process.exit(failed.length === 0 ? 0 : 1);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    process.stderr.write(`${err.stack ?? err}\n`);
    process.exit(1);
  });
}
