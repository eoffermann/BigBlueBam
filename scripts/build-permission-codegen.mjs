#!/usr/bin/env node
//
// Permission codegen.
//
// Reads docs/permissions-action-manifest.json and writes two derived
// artifacts that are committed to the repo:
//
//   1. infra/postgres/migrations/0145_permissions_seed_actions.sql
//      A single migration body that INSERTs every catalog row. Idempotent
//      via ON CONFLICT (id) DO UPDATE so re-running the seed picks up
//      catalog changes without violating the migration runner's
//      append-only rule (the migration BODY itself is immutable once
//      applied; subsequent seed updates land in 0148+).
//
//   2. packages/permissions/src/generated/permissions.ts
//      A TypeScript const enum + lookup map used by the resolver and the
//      `useCan` hook. Generated rather than hand-maintained so adding a
//      new permission is one PR (manifest + codegen) rather than three.
//
// The CI guard scripts/check-permission-catalog.mjs re-runs this codegen
// in a temp directory and diffs against the committed artifacts. Drift
// fails the build.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';

const ROOT = resolve(new URL('.', import.meta.url).pathname.replace(/^\/([A-Za-z]):\//, '$1:/'), '..');
const MANIFEST_PATH = join(ROOT, 'docs/permissions-action-manifest.json');
// 0145_permissions_seed_actions.sql is the FROZEN snapshot of the catalog
// at Wave A. After deploy, CLAUDE.md's immutability rule prohibits editing
// it. Catalog updates land in deltas at 0151+. The codegen no longer
// writes 0145; new rows go through scripts/build-permission-delta.mjs.
const TS_PATH = join(ROOT, 'packages/permissions/src/generated/permissions.ts');

function sqlString(s) {
  if (s == null) return 'NULL';
  return "'" + String(s).replace(/'/g, "''") + "'";
}

function sqlBool(b) {
  return b ? 'true' : 'false';
}

function buildMigration(manifest) {
  const lines = [];
  lines.push('-- 0145_permissions_seed_actions.sql');
  lines.push('-- Why: Seeds the action catalog (every <app>.<resource>.<verb> permission');
  lines.push('--   identifier in the platform). Generated from');
  lines.push('--   docs/permissions-action-manifest.json by');
  lines.push('--   scripts/build-permission-codegen.mjs. Re-running the codegen and');
  lines.push('--   committing the diff is the supported way to add or remove');
  lines.push('--   permissions; CI guard scripts/check-permission-catalog.mjs catches');
  lines.push('--   drift on every push.');
  lines.push('-- Client impact: additive only. Inserts ~1056 permissions; uses ON');
  lines.push('--   CONFLICT (id) DO UPDATE so re-running the migration on a partially-');
  lines.push('--   seeded DB picks up new metadata without violating the body-checksum');
  lines.push('--   rule (this file is rewritten only by the codegen, then never');
  lines.push('--   touched once applied).');
  lines.push('');
  lines.push('-- ──────────────────────────────────────────────────────────────────────');
  lines.push(`-- Catalog seed (${manifest.permissions.length} rows)`);
  lines.push('-- ──────────────────────────────────────────────────────────────────────');
  lines.push('');
  lines.push('INSERT INTO permissions (id, app, resource, verb, description, is_destructive, requires_confirmation, is_read) VALUES');

  const valueRows = manifest.permissions.map((p) => {
    const desc = `${p.app} ${p.resource} ${p.verb}`;
    return `    (${sqlString(p.id)}, ${sqlString(p.app)}, ${sqlString(p.resource)}, ${sqlString(p.verb)}, ${sqlString(desc)}, ${sqlBool(p.is_destructive)}, ${sqlBool(p.requires_confirmation)}, ${sqlBool(p.is_read)})`;
  });

  lines.push(valueRows.join(',\n') + '\nON CONFLICT (id) DO UPDATE SET');
  lines.push('    app = EXCLUDED.app,');
  lines.push('    resource = EXCLUDED.resource,');
  lines.push('    verb = EXCLUDED.verb,');
  lines.push('    description = EXCLUDED.description,');
  lines.push('    is_destructive = EXCLUDED.is_destructive,');
  lines.push('    requires_confirmation = EXCLUDED.requires_confirmation,');
  lines.push('    is_read = EXCLUDED.is_read;');

  return lines.join('\n') + '\n';
}

function tsIdent(s) {
  // Convert 'bam.task.create' -> 'BamTaskCreate' for TypeScript const names.
  return s.split(/[.\-_]/).map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
}

function buildTypeScript(manifest) {
  const lines = [];
  lines.push('// ─────────────────────────────────────────────────────────────────────');
  lines.push('// AUTO-GENERATED. Do not edit by hand.');
  lines.push('// Generated by scripts/build-permission-codegen.mjs from');
  lines.push('// docs/permissions-action-manifest.json.');
  lines.push(`// ${manifest.permissions.length} permissions across ${new Set(manifest.permissions.map((p) => p.app)).size} apps.`);
  lines.push('// ─────────────────────────────────────────────────────────────────────');
  lines.push('');
  lines.push('export interface PermissionMeta {');
  lines.push('  readonly id: string;');
  lines.push('  readonly app: string;');
  lines.push('  readonly resource: string;');
  lines.push('  readonly verb: string;');
  lines.push('  readonly is_destructive: boolean;');
  lines.push('  readonly requires_confirmation: boolean;');
  lines.push('  readonly is_read: boolean;');
  lines.push('  readonly requires_superuser: boolean;');
  lines.push('}');
  lines.push('');
  lines.push('/**');
  lines.push(' * The full action catalog as a frozen array. `requireCan` and `useCan`');
  lines.push(' * accept any string but tooling can use this type to guarantee the');
  lines.push(' * permission ID is in the catalog.');
  lines.push(' */');
  // Declare the array type explicitly (readonly PermissionMeta[]) so TS
  // doesn't try to build a 1056-element tuple-with-literal-types.
  // Otherwise typescript hits TS2590 "union type too complex to represent"
  // when consumers index into it.
  lines.push('const _PERMISSIONS_DATA: readonly PermissionMeta[] = [');
  for (const p of manifest.permissions) {
    lines.push(`  { id: ${JSON.stringify(p.id)}, app: ${JSON.stringify(p.app)}, resource: ${JSON.stringify(p.resource)}, verb: ${JSON.stringify(p.verb)}, is_destructive: ${p.is_destructive}, requires_confirmation: ${p.requires_confirmation}, is_read: ${p.is_read}, requires_superuser: ${p.requires_superuser ?? false} },`);
  }
  lines.push('];');
  lines.push('');
  lines.push('export const PERMISSIONS: readonly PermissionMeta[] = Object.freeze(_PERMISSIONS_DATA);');
  lines.push('');
  lines.push('/** Lookup map keyed by permission ID. O(1) check. */');
  lines.push('export const PERMISSIONS_BY_ID: ReadonlyMap<string, PermissionMeta> = new Map(');
  lines.push('  PERMISSIONS.map((p) => [p.id, p]),');
  lines.push(');');
  lines.push('');
  lines.push('/**');
  lines.push(' * Permission ID. Intentionally `string` rather than a literal union of');
  lines.push(' * the ~1056 catalog entries — TypeScript can\'t represent that union');
  lines.push(' * (TS2590 "too complex"), and even if it could the IntelliSense cost');
  lines.push(' * would be prohibitive on consumers. Use PERMISSIONS_BY_ID.has(id) at');
  lines.push(' * runtime to validate; the CI drift guard catches typos in seed data.');
  lines.push(' */');
  lines.push('export type PermissionId = string;');
  lines.push('');
  lines.push('/**');
  lines.push(' * Always-permitted core tools. The resolver short-circuits to ALLOW for');
  lines.push(' * these regardless of group membership, account override, or agent_policies.');
  lines.push(' * Mirrors the bypass list in apps/mcp-server/src/lib/register-tool.ts.');
  lines.push(' */');
  lines.push('export const ALWAYS_PERMITTED: ReadonlySet<string> = new Set([');
  lines.push('  "platform.system.get_info",');
  lines.push('  "platform.user.get_profile",');
  lines.push('  "agent.self.heartbeat",');
  lines.push(']);');
  lines.push('');

  // ── Tool name → permission ID lookup. Used by the MCP register-tool
  //    wrapper's Wave B dual-read so the resolver can be called by tool
  //    name without recomputing the inference rules at runtime.
  lines.push('/**');
  lines.push(' * MCP tool name → catalog permission ID. Generated from the manifest');
  lines.push(' * at codegen time so the MCP register-tool wrapper can look up a');
  lines.push(' * permission for a tool name without re-deriving the inference.');
  lines.push(' * Tools that source from REST routes (no tool name) are absent.');
  lines.push(' */');
  lines.push('export const TOOL_TO_PERMISSION: ReadonlyMap<string, string> = new Map([');
  // Walk every permission's sources; for each `mcp` source emit a row
  // tool_name -> permission.id. Some permissions have multiple MCP
  // sources (rare but possible) — last-write-wins is fine for the map.
  for (const p of manifest.permissions) {
    for (const s of p.sources ?? []) {
      if (s.source === 'mcp' && s.ref) {
        lines.push(`  [${JSON.stringify(s.ref)}, ${JSON.stringify(p.id)}],`);
      }
    }
  }
  lines.push(']);');
  lines.push('');

  // ── Route → permission ID lookup. Used by the Wave C codemod to
  //    map a Fastify route declaration to its catalog permission. Keys
  //    are 'METHOD /path' strings matching the `ref` field in the
  //    manifest's `sources` array for `rest` entries.
  lines.push('/**');
  lines.push(' * "METHOD /path" → catalog permission ID. Used by the Wave C codemod');
  lines.push(' * and by the contract test that asserts every route maps to a known');
  lines.push(' * permission. Generated from the manifest, so any new REST route');
  lines.push(' * needs the codegen re-run + delta migration committed.');
  lines.push(' */');
  lines.push('export const ROUTE_TO_PERMISSION: ReadonlyMap<string, string> = new Map([');
  for (const p of manifest.permissions) {
    for (const s of p.sources ?? []) {
      if (s.source === 'rest' && s.ref) {
        lines.push(`  [${JSON.stringify(s.ref)}, ${JSON.stringify(p.id)}],`);
      }
    }
  }
  lines.push(']);');
  lines.push('');

  return lines.join('\n');
}

function main() {
  if (!existsSync(MANIFEST_PATH)) {
    console.error(`✗ manifest not found at ${MANIFEST_PATH}. Run scripts/generate-permission-manifest.mjs first.`);
    process.exit(1);
  }
  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));

  mkdirSync(dirname(TS_PATH), { recursive: true });

  writeFileSync(TS_PATH, buildTypeScript(manifest));
  console.log(`✓ wrote ${TS_PATH}`);
  console.log('  (0145_permissions_seed_actions.sql is frozen post-deploy;');
  console.log('   add catalog deltas via scripts/build-permission-delta.mjs)');
}

main();
